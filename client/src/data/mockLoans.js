export function getLoanById(id) {
  return mockLoans.find((loan) => loan.id === id)
}

export function getDashboardSummary(loans = mockLoans) {
  const activeLoans = loans.filter((loan) => loan.status === LOAN_STATUS.ACTIVE)
  const closedLoans = loans.filter((loan) => loan.status === LOAN_STATUS.CLOSED)

  return {
    totalLoans: loans.length,
    activeLoans: activeLoans.length,
    closedLoans: closedLoans.length,
    totalRemaining: activeLoans.reduce((sum, loan) => sum + loan.remainingBalance, 0),
    totalInterestPaid: loans.reduce((sum, loan) => sum + loan.interestPaid, 0),
  }
}
